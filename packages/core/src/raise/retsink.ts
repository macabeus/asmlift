// `pokeemerald:MathUtil_Div16:agbcc`, `pokeemerald:MathUtil_Div16Shift:agbcc`,
// `sa3:sub_8001FD4:agbcc`, `synthetic:armkeep:agbcc`, `synthetic:bgfixed:agbcc` — five of them MATCH
// today. Three clauses decide 0 rows, and they are not the same kind of zero:
//
//   • `compiler-hoists-single-set-arm` decides 0 SITES as well, which is the point of putting it
//     last, and is what `target.ts` claims for it. Moved back to first it collects 28 sites and
//     still moves 0 rows.
//   • `no-arrival-but-the-arms` and `pre-diamond` decide the SAME two sites
//     (`pokeemerald:GetGenderFromSpeciesAndPersonality:agbcc`,
//     `pokeemerald:TrySetCantSelectMoveBattleScript:agbcc`) and the order between them decides which
//     one the census bills. Both are merges with a third in-edge: `mergeArms` counts ALL
//     predecessors where `two-arms-one-head` counts only the `br` ones, so the pre-recovery map
//     already called them no diamond. NO MANUFACTURED DIAMOND REACHES THIS TABLE TODAY — the reason
//     is still `fusedDiamond` being tested first in the same disjunction, and `pre-diamond` is the
//     clause that stops that being an accident. Argued, not corpus-paid, and marked as such.
//   • `a-value-is-returned` first-refuses two agbcc sites (below) and is subsumed by
//     `arms-are-one-set` a step later.
//
// THE THREADING IS NOT FRAGILE, which was the open question when `pre-diamond` was proposed: of the
// 74 sites, ZERO find their merge block ABSENT from the pre-recovery map. Block identity survives
// all twelve pre-recovery passes, their eight `dce` runs and `recoverTypes`, so every refusal here
// is a real `diamond: false` and never a lost key.
//
// The named single-condition controls — `maxi`/`mini`/`absdiff`/`clamp0`/`bittest` — are NOT
// protected by any of these clauses, a claim this header used to make and which is false: agbcc
// emits those as a branch-over-one-instruction (or branchlessly), so their targets hold no two-armed
// diamond and `two-arms-one-head` has already refused them. A control that stays MATCH because it
// never reaches the table is not evidence the table is right — the shapes that DO reach it are the
// bodied ones above, and they are what `packages/cli/test/matching` pins.
//
// REACH: ONE corpus row. Re-lifting all 1039 rows against `origin/main` changes the emitted source
// of `kleod:IsSelectButtonPressed:agbcc` and of nothing else. FAILURE DIRECTION: a wrong admission
// costs a SPELLING and never an answer — the transform is a tail duplication, every arm keeps the
// value it carried — which is why every clause here is `sound: false`.
//
// SINKING IS NECESSARY, NOT SUFFICIENT: `/flip-branch` was necessary on 4 of the 4 inhabitants
// measured (`if (x & 0x40) return 1; return 0;` and its inverse, `if (x > 3) return 5; return 3;`,
// `if (x == 0) return 1; return 0;`). Unranked, all four score 3 and none matches; the target row's
// own label moved `unsigned` → `unsigned/flip-branch`. The mechanism is structural rather than a
// property of the sample: a sunk diamond has NO JOIN left, so the shipped joined-if default (the
// layout reading) does not cover it, and for a constant-arm diamond agbcc puts the source's taken
// arm in the FAR block, which makes the layout reading systematically inverted. "Both arms return a
// constant" is a per-SITE fact this pass holds at the moment it fires, so emitting the target's
// sense HERE would move the unranked path too — the CLI one-shot, apps/web's preset, and
// `packages/cli/test/matching`, none of which the ranked fan rescues. That is a separate round with
// its own regression surface (`regression.test.ts`'s fixtures, the byte-pinned playground preset)
// and is booked rather than bundled.
//
// WHY A GATE AND NOT AN AXIS, since `l3/unmerge.ts` is this tree's other "duplicate a join back
// into the arms" pass and IS one. `unmerge.ts` is an axis on the stated grounds that the mapping
// from its tree back to a source is not a function and not uniformly many-to-one — which way it
// goes is a property of the SHAPE, and no gate there can read that off the tree. This admission
// asserts the opposite for its own shape, and the assertion is what `arms-are-one-set` IS: on the
// axis that clause reads, the mapping is a function, the differ never has to referee it, and the fan
// does not grow (4 candidates before, 4 after). An axis where a default belongs doubles every
// enumeration to referee a question with one answer.
//
// WHAT MOVES THE THING THIS DEFAULT PLACES. `docs/level-tower.md:135-140`: a per-compiler default
// read backwards "owes an explicit refusal for every pass that moves the thing it is placing".
// The thing placed is a TWO-ARMED DIAMOND, and asmlift manufactures one. `raise/shortcircuit.ts`'s
// `branch-shortcircuit` builds diamonds out of condition trees the ROM never merged — measured in
// `narrowlocal.ts`'s `mergeShapes` header, where 20 sa3 blocks gain `diamond` between lift and
// pre-recovery's end and that pass accounts for all 10 that gain `hoistable`. `sinkReturns` runs
// LATER STILL (`pipeline.ts`: after all twelve pre-recovery passes, eight of them followed by `dce`,
// and after `recoverTypes`), so it sees every one of them.
//
// THE REFUSAL IS `pre-diamond`, and it is the same answer narrowlocal reached: the shape is read
// from `PreRecoveryFacts.mergeShapes`, computed ONCE on the CFG as it ENTERS pre-recovery and
// threaded down. A merge block absent from that map — created by a later pass — reads as no diamond
// and is refused. A manufactured diamond therefore cannot be mistaken for one the ROM held, which is
// the whole content of the backwards read.
//
// IT IS AN ARGUED GUARD AND NOT A CORPUS-PAID ONE, and the honest version of the claim is this: no
// manufactured diamond reaches this table today, because `fusedDiamond` is tested before
// `constantSelect()` in the same disjunction, so a `logic_and`-fused manufacture takes the
// short-circuit path instead. That is a coincidence of evaluation order on a corpus with exactly ONE
// admit site — nothing here could have caught it changing — and `pre-diamond` is what makes the
// refusal stated rather than accidental. This file's own history is the hazard having already fired
// once: a branch-shortcircuit fusion destroyed the CFG signal these clauses gate on, and
// `if (a && b) return X; return Y;` stopped matching byte-exact with no hosted gate noticing. The
// fixture that pins it (`retsink.test.ts`) therefore has to build the divergence by hand — a live
// diamond the pre-recovery map does not have — because the corpus does not supply one.
// What the clause does NOT claim to cover is the second half of the tower's sentence — an IR
// boundary the FRONTEND invents. `mergeShapes`' own header names that residue (the frontend cuts
// blocks at labels, `applyIdiomPatterns` folds shift pairs, both before pre-recovery runs, and both
// only ever make an arm SHORTER), and it is inherited here unchanged rather than re-argued.
//
// THE QUANTITY IS ARRIVALS, NOT PREDECESSORS. A FALL-THROUGH switch arm is the difference:
// `case 2: r++; case 1: r++;` gives case 1's body two predecessors — the dispatch's `beq`, and
// case 2's body running on — for a reason that has nothing to do with a chain of conditions.
// Sinking there tail-duplicates the switch's SHARED RETURN into all five of its paths, which agbcc
// then constant-folds per arm (`synthetic:sw_fall:agbcc`, 5 of its 11 objdiff points).
//
// So one arrival is SUBTRACTED, and only one kind: the previous arm of the same dispatch RUNNING
// ON into this one (`fellInto`). It is subtracted for what it IS, not for what it computed —
// "this pred computed something and ran on" is a proxy for the same intuition, and it refuses the
// shape this pass exists for, where the two arms of `if (a) { … return 0; } if (b) { … return 0; }`
// both compute and both jump to the shared exit (`retsink.test.ts`'s `TWO_ARMS`; five real-tier
// sites have it, `kleod:EntityItemDrop:agbcc` among them).
//
// "THE PREVIOUS ARM OF THE SAME DISPATCH" IS A CLAIM ABOUT A DISPATCH, so this file models one
// (`scrutOf`/`armsOf` below): two arms of two DIFFERENT tests on the SAME scrutinee. A proxy that
// does not name a dispatch is wrong in both directions, and both readings are pinned as fixtures —
// "each is the target of SOME conditional branch" reads the join of an `if` with no `else` as a
// fall-in (`IF_NO_ELSE`), and adding "…and not siblings of the same `cond_br`" still says nothing
// about WHICH dispatch, so `if (a) … if (b) …` on two different values loses its sinking. A
// function with no comparison-tree dispatch has no fall-in to subtract, which is the truth about it.
//
// The two other clauses (`FALL_IN_GATES`): `q` must arrive by an UNCONDITIONAL branch, and it must
// have a BODY. `isBodyless` (ir/core.ts) is the shared spelling of the second — a bodyless arm is
// the record gcc leaves of a decision that RAN OUT (`emit_case_nodes` mints a `b .Ldefault` per
// exhausted subtree), and it arrives rather than falls in; dropping it costs
// `synthetic:llshr:gcc2.7.2kmc` its sinking. Its parameter half is what keeps an EMPTY case arm
// (one op, but it binds the accumulator) on the fall-in side.
//
// AND THE MERGE MUST BELONG TO THAT DISPATCH (`ownedBy`). A fall-through switch can SHARE its
// return with control flow outside itself — a guard's `goto` onto the same `return` — and there
// refusing to sink is exactly wrong: the merge is left standing, Regime-A switch recovery declines
// on it, and if-recovery duplicates the tails anyway. The pred shape alone cannot tell the two
// apart (both present one fell-into arm with two preds); the SCRUTINEE can, because the guard tests
// a different value. `synthetic:sw_fallguard` is the row: MATCH, and diff:6 with the clause dropped.
//
// REGIME SCOPE — the model is `cond_br`-seeded, so it is INERT ON A JUMP TABLE. A `switch_br`
// dispatch's arms are invisible to `armsOf` and `fellInto` never fires there, so on
// `synthetic:sw_jtfall`/`sw_jtfalldesc` the pass behaves as it does where there is no dispatch at
// all. Deliberate: seeding `switch_br` too would move matching rows with no row asking for it. It
// is the second definition of "this arm falls into that one" in the tree — `switch-recover.ts`'s
// `analyzeArmExit` covers both regimes and is not reachable from `raise/` — so whoever builds the
// Regime-B hoist should route both through one recognizer rather than widen the seed here.
//
// This does NOT recover the boolean-VALUE form `return a && b` — that is shortcircuit.ts's job
// (the `logic_and`/`logic_or` connective plus agbcc's `(-b|b)>>31` = `b!=0` normalisation).
