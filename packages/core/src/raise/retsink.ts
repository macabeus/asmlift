//
// WHAT EACH CLAUSE ACTUALLY DECIDES, measured by ablating it and re-lifting all 1039 corpus rows
// offline (`targetAsm` out of the artifact, source-hash diff), ON THE TABLE AS IT STANDS — a number
// here is only true of the clause ORDER it was measured under, which a previous revision of this
// header learned by carrying a "the pair decides 8" across the commit that moved the compiler clause
