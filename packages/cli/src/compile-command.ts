/** Compile one candidate translation unit into a relocatable object; returns the object path.
 *  Throws on any failure — a candidate that cannot be compiled must never score.
 *
 *  `declarations` (optional) is the candidate's SYNTHESIZED declaration block (declare.ts —
 *  self-declaring candidates): joined to the typedef prelude in the self-declared world,
 *  dropped with it in the headers world (the probe below arbitrates). Compilers that inject
 *  their own context (the benchmark's vendored-ctx real-tier compile, @asmlift/toolchains)
 *  simply ignore the argument — their context IS the headers world. */
export type CandidateCompiler = (source: string, symbol: string, backendId: string, declarations?: string) => string;

/** The same contract, run without blocking the event loop, so several candidates can compile at
 *  once. Each worker owns its own scratch slot, so one worker's object survives exactly until
 *  that worker compiles its next candidate — the caller must consume it before asking for
 *  another (`rank.ts`'s pool scores each object the moment it lands). */
export type AsyncCandidateCompiler = (
  source: string,
  symbol: string,
  backendId: string,
  declarations?: string,
) => Promise<string>;

/** One compiler instance in both flavours. `compile` is the synchronous contract every existing
 *  caller uses; `worker()` mints an INDEPENDENT async compiler with its own scratch slot — call
 *  it once per pool worker. Both share the one cached world probe below. */
export interface CommandCompilers {
  compile: CandidateCompiler;
  worker: () => AsyncCandidateCompiler;
  /** Which WORLD the probe found, or undefined before the first candidate compiled: `true` =
   *  SELF-DECLARED (this template compiles bare candidates, so asmlift's synthesized declaration
   *  block is part of every score), `false` = HEADERS (the block is dropped, the project owns the
   *  declarations). Exposed because the caller publishing a score has to say whether that score
   *  rests on declarations asmlift invented — and only the probe knows. */
  selfDeclared: () => boolean | undefined;
}

export interface CompileCommandOptions {
  /** Working directory for the command — the decomp.yaml's directory, so project-relative
   *  paths (`./tools/agbcc/bin/agbcc`) resolve regardless of where asmlift was invoked. */
  cwd?: string;
  /** `tools.asmlift.cacheInputs` — the project's DECLARATION of every file and directory its
   *  compile command reads. It is the contract that lets the cross-run candidate-object cache
   *  run on this template AT ALL: absent, the cache stays off here, however fast it would be.
   *
   *  A namespace can only measure inputs it can name. Files the template names as TOKENS are
   *  found automatically; an input reached through a DIRECTORY (`-I ./inc` plus a candidate's
   *  `#include "k.h"`) is in no token set and no probe TU exercises it — editing `k.h` between
   *  two runs served a stale object. Declaring the directory is what makes it visible. */
  cacheInputs?: readonly string[];
}

// Substituted values are injected RAW so the template owns its quoting (a natural template
// writes `PRE="{out}.i"` — a pre-quoted substitution would put literal quotes in the
// filename). The guarantee instead: every substituted value is shell-inert, or the compile
// throws. Paths come from mkdtemp (always safe); the symbol can come from UNVALIDATED
// pasted-asm labels, so this check is load-bearing against shell injection.
const SHELL_SAFE = /^[A-Za-z0-9_./+-]+$/;
const safe = (value: string, what: string): string => {
  if (!SHELL_SAFE.test(value)) {
    throw new Error(`${what} contains shell-unsafe characters, refusing to substitute: ${JSON.stringify(value)}`);
  }
  return value;
};

/** Build a CandidateCompiler from a `decomp.yaml` command template. `{{inputPath}}` and
 *  `{{outputPath}}` are REQUIRED placeholders (substituted with absolute paths);
 *  `{{symbol}}` is optional. The placeholder style matches other decomp tools' `compiler`
 *  templates, so a project's tool blocks read uniformly. The command runs via `sh -ec` — EVERY
 *  step must succeed, not just the last one: gcc-2.9-family compilers exit nonzero on a hard
 *  error (an undeclared identifier, even an invalid flag) yet still write a PARTIAL .s with the
 *  erroring statements deleted, so without `-e` a later assemble step "succeeds" and a silently
 *  TRUNCATED object gets scored (found scoring real 22/28/38 phantoms in the klonoa dogfood).
 *  A non-zero exit or a missing output object throws with the full command + its stderr —
 *  configured means configured, there is no fallback. */
export function compilersFromCommand(template: string, opts: CompileCommandOptions = {}): CommandCompilers {
  if (!template.includes('{{inputPath}}') || !template.includes('{{outputPath}}')) {
    throw new Error(`compiler command must contain {{inputPath}} and {{outputPath}} placeholders — got: ${template}`);
  }
  // An unrecognized {{...}} placeholder is a config mistake (e.g. another tool's
  // {{functionName}} pasted verbatim) — name it now instead of a baffling shell failure.
  const unknown = template.replaceAll(/\{\{(inputPath|outputPath|symbol)\}\}/g, '').match(/\{\{\w+\}\}/);
  if (unknown) {
    throw new Error(
      `compiler command has an unknown placeholder ${unknown[0]} — supported: {{inputPath}}, {{outputPath}}, {{symbol}}`,
    );
  }
  // ONE scratch directory per WORKER, emptied before each compile — not one per candidate.
  // mkdtemp never removes anything, so a per-candidate directory leaked one per compile: a
  // ranked run over 20k candidates left 20k of them behind, and the temp dir had accumulated
  // 1.5M. Emptied rather than reused: a step that exits 0 without writing its output must still
  // fail LOUD, and a surviving sibling from the previous candidate is exactly what would let it
  // pass (the same class of silent truncation the `sh -ec` note above is about).
  //
  // Reuse is safe HERE because the template runs a fresh process per compile against the host
  // filesystem. It is NOT safe for a template that keeps a long-lived container with this
  // directory's parent bind-mounted: the benchmark's dockerized toolchains measured ~30% of
  // compiles failing on a reused path (apps/benchmark/src/compile/util.ts `scratchSlot`), which
  // is why they still mkdtemp per candidate.
  const slot = (): (() => string) => {
    let dir: string | undefined;
    return () => {
      if (dir === undefined) {
        dir = mkdtempSync(join(tmpdir(), 'asmlift-usercc-'));
        return dir;
      }
      rmSync(dir, { recursive: true, force: true });
      mkdirSync(dir);
      return dir;
    };
  };

  // One template execution, in two halves: `stage` writes the input and builds the command,
  // `verdict` reads the exit status — shared verbatim by the sync and async runners so the two
  // can never diverge on what counts as a failed compile or on how it is reported.
  //
  // `transient` is the half a MESSAGE cannot carry: this machine had a bad minute, the compiler
  // never gave a verdict, and nothing about the outcome may be stored.
  type Verdict = { ok: boolean; transient: boolean; cmd: string; err: string };
  const stage = (dir: string, content: string, symbol: string, ext: 'c' | 'p') => {
    const inPath = join(dir, `cand.${ext}`);
    const outPath = join(dir, 'cand.o');
    writeFileSync(inPath, content);
    const cmd = template
      .replaceAll('{{inputPath}}', safe(inPath, '{{inputPath}}'))
      .replaceAll('{{outputPath}}', safe(outPath, '{{outputPath}}'))
      .replaceAll('{{symbol}}', safe(symbol, 'the symbol name'));
    return { outPath, cmd };
  };
  // The scratch DIRECTORY is collapsed out of every failure message. It is an mkdtemp accident:
  // two runs of the identical failure print different text, so a rejection replayed from the cache
  // (which stores the message from the run that produced it) would not be equal in RESULT to a
  // fresh one — and the ranked path publishes that first line as `dropped[].error`. Collapsing it
  // makes the cached and uncached spellings identical, and takes a machine path out of published
  // output at the same time.
  const verdict = (status: number | null, output: string, cmd: string, outPath: string): Verdict => {
    const scrub = (t: string): string => t.split(dirname(outPath)).join('<scratch>');
    // A KILLED compile is not a rejection, and `sh` is what hides that here. The template always
    // runs through `sh -ec`, and a shell reports a killed child as exit 128+signal — a SIGKILLed
    // compiler arrives as a perfectly ordinary `exit 137`, which the negative-entry guard matched
    // and stored FOREVER (`sh: line 1: 15022 Killed: 9` in the stored body). Reach is not
    // hypothetical: candidate compiles have no timeout, `docker run` exits 137 on an OOM-killed
    // container, and a bench run forks 8–16 shards. `status === null` is the same thing when the
    // shell ITSELF is killed. Both are transient and neither may be stored.
    if (status === null || status >= 128) {
      return {
        ok: false,
        transient: true,
        cmd,
        err: scrub(
          `compile command did not run to completion (${status === null ? 'killed by a signal' : `exit ${status} — killed by signal ${status - 128}`}): ` +
            `${cmd}\n${output.trim()}`,
        ),
      };
    }
    if (status !== 0) {
      return {
        ok: false,
        transient: false,
        cmd,
        err: scrub(`compile command failed (exit ${status}): ${cmd}\n${output.trim()}`),
      };
    }
    if (!existsSync(outPath)) {
      return {
        ok: false,
        transient: false,
        cmd,
        err: scrub(`compile command exited 0 but produced no object at {{outputPath}}: ${cmd}`),
      };
    }
    return { ok: true, transient: false, cmd: outPath, err: '' };
  };

  const mainSlot = slot();
  const execute = (content: string, symbol: string, ext: 'c' | 'p'): Verdict => {
    const { outPath, cmd } = stage(mainSlot(), content, symbol, ext);
    const r = spawnSync('sh', ['-ec', cmd], { encoding: 'utf8', cwd: opts.cwd });
    return verdict(r.status, r.stderr || r.stdout, cmd, outPath);
  };
  // Two DEDICATED slots for the namespace stamp probe. Never `mainSlot`: the stamp is reached
  // from `warm()` and, compiled into the slot a candidate has just written, it overwrites that
  // candidate's object — measured once as 8 poisoned keys, 26 moved report fields and 2 rows
  // flipped nonmatch to noncompile, with every other gate green.
  const stampSlot = slot();
  const stampSlot2 = slot();
  const executeInSlot = (dir: string, content: string, symbol: string, ext: 'c' | 'p'): Verdict => {
    const { outPath, cmd } = stage(dir, content, symbol, ext);
    const r = spawnSync('sh', ['-ec', cmd], { encoding: 'utf8', cwd: opts.cwd });
    return verdict(r.status, r.stderr || r.stdout, cmd, outPath);
  };
  const executeIn = (dir: string, content: string, symbol: string, ext: 'c' | 'p') =>
    new Promise<Verdict>((res) => {
      const { outPath, cmd } = stage(dir, content, symbol, ext);
      const p = spawn('sh', ['-ec', cmd], { cwd: opts.cwd });
      let out = '',
        err = '';
      // DECODED as it arrives, not concatenated as Buffers: `'' + buf` decodes each chunk on its
      // own, so a multi-byte character straddling a chunk boundary would come out as replacement
      // characters here and not in the sync runner (spawnSync decodes the whole buffer at once).
      // The two must report a failed compile with the same text.
      p.stdout.setEncoding('utf8');
      p.stderr.setEncoding('utf8');
      p.stdout.on('data', (d: string) => (out += d));
      p.stderr.on('data', (d: string) => (err += d));
      // A shell that never starts is reported like any other failed compile, not as a rejected
      // promise: the ranked driver reads a THROWN compile the same way whichever runner produced
      // it, and a second `res` after `close` is a no-op.
      p.on('error', (e) =>
        res({ ok: false, transient: true, cmd, err: `compile command failed to start: ${cmd}\n${e.message}` }),
      );
      p.on('close', (code) => res(verdict(code, err || out, cmd, outPath)));
    });

  // Which WORLD candidates compile in — PROBED, never configured. Two worlds exist:
  //   • SELF-DECLARED: a bare template compiles the candidate alone, so it needs asmlift's
  //     typedef prelude plus the candidate's synthesized declaration block (declare.ts);
  //   • HEADERS: the template injects project headers, which already own u8/u16/… AND every
  //     global/struct declaration — C89 hard-errors on a duplicate typedef and on a duplicate
  //     struct definition, so prelude and synthesized decls must BOTH be dropped.
  // The compiler itself is the only authority, so ask it once: compile the prelude + a
  // REPRESENTATIVE declaration block (one exemplar of every construct synthesis emits) + one
  // harmless decl. The block is representative rather than per-candidate because decls vary
  // per candidate while the verdict is per COMPILER INSTANCE (cached) — and real blocks use
  // exactly this vocabulary, so accepting the exemplar accepts them all.
  // Success ⇒ self-declared world. Failure ⇒ try the bare decl alone: success confirms the
  // headers collision (drop prelude + decls); failure means the TEMPLATE is broken — keep
  // everything so the first real candidate fails with the template's own loud diagnostics.
  // Exit-code-only: no error-message parsing (gcc-2.9/IDO/mwcc all format differently).
  // The cross-run candidate-object cache on the project-template path (candcache.ts). OFF unless
  // ASMLIFT_CANDCACHE, and OFF unless the project DECLARED `tools.asmlift.cacheInputs`.
  //
  // The NAMESPACE is a measurement, not a version constant: the template text, the cwd, the
  // content hash of every DECLARED input, of every existing file the template names
  // (`./tools/agbcc/bin/agbcc`, `tools/preproc/preproc`, `charmap.txt`), of every command it
  // resolves on $PATH, the value of every environment variable it reads, and, decisively, the
  // OBJECT BYTES this very template produces for one fixed probe TU, compiled twice in two
  // different directories so the compiler itself answers whether its output is a pure function
  // of its input.
  const sha256 = (b: Buffer | string): string => createHash('sha256').update(b).digest('hex');
  /** A file the shell would RUN, as opposed to one a compile merely reads. Only those have a
   *  delegate chain worth following. */
  const isExecutableFile = (p: string): boolean => {
    try {
      const st = statSync(p);
      return st.isFile() && (st.mode & 0o111) !== 0;
    } catch {
      return false;
    }
  };
  const hashPath = (h: ReturnType<typeof createHash>, tag: string, p: string): boolean => {
    try {
      const st = statSync(p);
      if (st.isDirectory()) {
        // A DECLARED directory is hashed by its whole contents, recursively and in sorted order:
        // that is the entire point of the declaration (`-I ./inc` reaches `inc/k.h`, which no
        // token set and no probe TU can see).
        h.update('dir:' + tag);
        for (const e of readdirSync(p, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
          hashPath(h, tag + '/' + e.name, join(p, e.name));
        }
        return true;
      }
      if (!st.isFile()) {
        return false;
      }
      h.update(tag);
      h.update(sha256(readFileSync(p)));
      return true;
    } catch {
      return false;
    }
  };
  /** One entry of a delegate chain. A measurement entry (`UNRESOLVED:`, `ENV:`) is hashed as the
   *  STRING it is — it is an answer, not a file, and skipping it drops the answer. A file is
   *  hashed by CONTENT under its BASENAME, never its absolute path: two worktrees of this repo
   *  hold byte-identical toolchains at different paths, and keying on the path gives each its own
   *  namespace, so every parallel round cold-starts and leaves a second store behind. */
  const hashChain = (h: ReturnType<typeof createHash>, tok: string, entry: string): void => {
    if (isChainMeasurement(entry)) {
      h.update(tok + '>' + entry);
      return;
    }
    hashPath(h, tok + '>' + basename(entry), entry);
  };
  // ABSENT and EMPTY are different answers. `cacheInputs: []` is a project SAYING "this template
  // reads nothing my tokens do not already name"; no key at all is a project that has not been
  // asked. Only the second turns the cache off.
  if (
    opts.cacheInputs !== undefined &&
    (!Array.isArray(opts.cacheInputs) || opts.cacheInputs.some((d) => typeof d !== 'string' || d.trim() === ''))
  ) {
    // The same contract `config.ts` enforces on the YAML, enforced again at the API: a STRING
    // reaching this list iterates per character, and three `MISSING` characters hash to the same
    // digest as three declared files that are not there — the cache on, the declaration measured,
    // and nothing of the project actually in the namespace.
    throw new Error(
      `cacheInputs must be an array of non-empty path strings, got ${JSON.stringify(opts.cacheInputs)} — ` +
        `it is the candidate-object cache's contract, not a hint`,
    );
  }
  const declared = opts.cacheInputs ?? [];
  const declaredCompileInputs = opts.cacheInputs !== undefined;
  const stamp = (): string => {
    const h = createHash('sha256');
    const cwd = resolve(opts.cwd ?? process.cwd());
    h.update('command/v1');
    h.update(template);
    h.update(cwd);
    // THIS MODULE'S OWN BYTES. The bench pipeline hashes its harness code (`compile/agbcc.ts`,
    // `compile/util.ts`) because that code shapes what the compiler is handed; this one shapes it
    // too, and it shapes something the probe object structurally cannot see — 77% of what a warm
    // store SERVES is a stored REJECTION, and `verdict()` above builds the text that is stored and
    // then published as `ranked.dropped[].error`. The probe only ever exercises the success path,
    // so perturbing that text left the namespace unmoved and the store replayed the old spelling.
    // Cheap, too: this file has moved 3 times in the repo's whole history, against 4 for
    // `compile/util.ts`, which has been in a namespace all along.
    h.update('self:');
    h.update(sha256(readFileSync(fileURLToPath(import.meta.url))));
    // (0) every DECLARED input, by content: files and whole directory trees.
    for (const d of declared) {
      const p = isAbsolute(d) ? d : resolve(cwd, d);
      h.update('declared:' + d);
      if (!hashPath(h, 'declared:' + d, p)) {
        // A declared input that is not there means the project's contract is STALE. It is still
        // hashed as MISSING (so the namespace moves the day it appears), but silence here is how
        // a declaration stops describing the compile it is the contract for.
        h.update('MISSING');
        process.stderr.write(
          `[candcache] declared cacheInputs entry does not exist: ${d} (resolved ${p}) — the declaration is the contract, and this one names nothing\n`,
        );
      }
    }
    // (1) every template token that names an existing FILE: the project's own
    //     `./tools/agbcc/bin/agbcc`, `tools/preproc/preproc`, `charmap.txt`, hashed by content.
    // (2) every remaining token that RESOLVES ON $PATH: `arm-none-eabi-cpp`, `arm-none-eabi-as`,
    //     `cc`, hashed by content too. MEASURED WHY: the probe object below did NOT move between
    //     two different pinned agbcc revisions (they agree on the probe TU), so a namespace
    //     resting on the probe alone would have served one compiler's objects for the other.
    // (3) every shell variable the template READS but does not itself assign: that is an
    //     external input choosing the compiler, so its value (and its content, if it names a
    //     file) joins the stamp.
    const assigned = new Set<string>();
    for (const m of template.matchAll(/^\s*([A-Za-z_]\w*)=/gm)) {
      assigned.add(m[1]);
    }
    const seen = new Set<string>();
    const seenEnv = new Set<string>();
    for (const tok of template.split(/[\s"'<>|;()]+/)) {
      if (!tok || tok.startsWith('{{') || tok.length > 300 || seen.has(tok)) {
        continue;
      }
      seen.add(tok);
      const asPath = isAbsolute(tok) ? tok : resolve(cwd, tok);
      if (/[/.]/.test(tok) && hashPath(h, tok, asPath)) {
        // A token that names an EXECUTABLE file (`./tools/agbcc/bin/agbcc`) can be a wrapper too,
        // so follow it as well; a plain data file (`charmap.txt`) has no chain and costs one stat.
        if (isExecutableFile(asPath)) {
          for (const f of toolchainFileChain(asPath)) {
            hashChain(h, tok, f);
          }
        }
        continue;
      }
      if (/^[A-Za-z][\w.+-]*$/.test(tok)) {
        // Not "the file this name resolves to" — the whole CHAIN that actually runs. A `cpp` that
        // is a `#!/bin/sh` shim exec'ing `cpp-14`, or a gcc driver exec'ing `cc1`, has its
        // compiler one level past the file a namespace would otherwise hash; repointing the
        // delegate served a stale object with the outer file byte-identical. `toolchainFileChain`
        // THROWS where it cannot follow, and `candCache` turns that into a loud refusal.
        for (const f of toolchainFileChain(tok)) {
          hashChain(h, tok, f);
        }
      }
    }
    // (3b) the compile ENVIRONMENT gcc/cpp read whether or not the template mentions it — the one
    // list, shared with the bench's agbcc pipeline (candcache.ts `COMPILE_ENV`).
    for (const v of COMPILE_ENV) {
      h.update(`compileenv:${v}=${process.env[v] ?? ''}`);
    }
    for (const m of template.matchAll(/\$\{?([A-Za-z_]\w*)\}?/g)) {
      const v = m[1];
      if (assigned.has(v) || seenEnv.has(v)) {
        continue;
      }
      seenEnv.add(v);
      const val = process.env[v] ?? '';
      h.update('env:' + v + '=' + val);
      if (val) {
        hashPath(h, 'env:' + v, isAbsolute(val) ? val : resolve(cwd, val));
      }
    }
    // (4) BACKSTOP + DETERMINISM SELF-TEST, in one measurement. The object bytes this template
    // produces for one fixed probe TU, compiled TWICE in two different directories. Identical
    // means the object is a pure function of its input and the bytes join the namespace;
    // different means NOT_CACHEABLE, refused out loud. MEASURED: `ido7.1` writes the absolute
    // path of its input .c into the object (1108 vs 1124 bytes at two scratch paths); agbcc does
    // not.
    const d1 = stampSlot();
    const d2 = stampSlot2();
    const p1 = executeInSlot(d1, STAMP_PROBE, 'asmlift_candcache_stamp', 'c');
    const p2 = executeInSlot(d2, STAMP_PROBE, 'asmlift_candcache_stamp', 'c');
    const answer = ((): string => {
      if (!p1.ok || !p2.ok) {
        return NOT_CACHEABLE;
      }
      const b1 = sha256(readFileSync(p1.cmd));
      if (b1 !== sha256(readFileSync(p2.cmd))) {
        return NOT_CACHEABLE;
      }
      h.update(b1);
      return h.digest('hex');
    })();
    // mkdtemp removes nothing: two probe directories per process, forever, is the leak
    // `scratchSlot` was written to stop.
    rmSync(d1, { recursive: true, force: true });
    rmSync(d2, { recursive: true, force: true });
    return answer;
  };
  // OPT-IN, per project. A cache on the path every published score comes from is only as sound
  // as the list of inputs it was told about, so the declaration IS the contract: no
  // `tools.asmlift.cacheInputs` key, no cache here — but an EMPTY list is still a declaration.
  const cache = declaredCompileInputs ? candCache('command', stamp) : OFF_CACHE;
  // A negative entry is only sound for a DETERMINISTIC rejection: the template RAN and exited
  // nonzero. `compile command failed to start` (a missing shell, a fork failure) and a killed
  // process must never be stored: a transient would then drop that candidate on every future
  // run, which is the silent-wrong-answer shape this repo bans.
  const DETERMINISTIC_REJECTION = /^compile command (failed \(exit \d+\)|exited 0 but produced no object)/;
  /** A rejection is storable only when the SPAWN RESULT says the compiler gave a verdict, and only
   *  when the message has the shape one has. Two guards, because each has been the one that held:
   *  the message shape alone stored a SIGKILL laundered by `sh` into `exit 137`. */
  const storableRejection = (r: Verdict): boolean => !r.transient && DETERMINISTIC_REJECTION.test(r.err);
  // A candidate TU whose object is not a function of its own bytes is refused PER KEY, keeping the
  // cache on for every other candidate. Two shapes, both in `candidateCacheRefusal` (shared with
  // the bench pipeline, because a predicate copied into two files is a predicate fixed in one):
  // a TU that READS A FILE — the path lives in the TU, not in the template's tokens, and no probe
  // exercises it — and a TU that bakes its own path or the clock in via `__FILE__` / `__DATE__`.
  const cacheable = (content: string): boolean => {
    if (cache.mode === 'off') {
      return false;
    }
    const reason = candidateCacheRefusal(content);
    if (reason === undefined) {
      return true;
    }
    noteKeyRefused('command', reason);
    return false;
  };
  const viaCache = (content: string, symbol: string, ext: 'c' | 'p', raw: () => Verdict): Verdict => {
    if (!cacheable(content)) {
      return raw();
    }
    const key = ext + ' ' + content;
    if (cache.mode === 'on') {
      const hit = cache.get(key, symbol);
      if (typeof hit === 'string') {
        return { ok: true, transient: false, cmd: hit, err: '' };
      }
      if (hit instanceof Error) {
        return { ok: false, transient: false, cmd: '', err: hit.message };
      }
    }
    const r = raw();
    if (r.ok) {
      cache.verify(key, symbol, r.cmd);
      return { ok: true, transient: false, cmd: cache.put(key, symbol, r.cmd), err: '' };
    }
    if (cache.mode !== 'off' && storableRejection(r)) {
      // verifyFail FIRST: a STORED OBJECT for a TU that no longer compiles is a mismatch, and it
      // is the direction that nothing audited — 77% of a warm store's served answers are
      // rejections and verify mode never looked at one.
      cache.verifyFail(key, symbol, r.err);
      cache.putFail(key, symbol, r.err);
    }
    return r;
  };
  const executeCached = (content: string, symbol: string, ext: 'c' | 'p'): Verdict =>
    viaCache(content, symbol, ext, () => execute(content, symbol, ext));
  // NOTE the slot is a THUNK: on a cache hit the worker's scratch dir is never emptied and
  // recreated, which is the whole point of not spawning.
  const executeInCached = async (
    dir: () => string,
    content: string,
    symbol: string,
    ext: 'c' | 'p',
  ): Promise<Verdict> => {
    if (!cacheable(content)) {
      return executeIn(dir(), content, symbol, ext);
    }
    const key = ext + ' ' + content;
    if (cache.mode === 'on') {
      const hit = cache.get(key, symbol);
      if (typeof hit === 'string') {
        return { ok: true, transient: false, cmd: hit, err: '' };
      }
      if (hit instanceof Error) {
        return { ok: false, transient: false, cmd: '', err: hit.message };
      }
    }
    const r = await executeIn(dir(), content, symbol, ext);
    if (r.ok) {
      cache.verify(key, symbol, r.cmd);
      return { ok: true, transient: false, cmd: cache.put(key, symbol, r.cmd), err: '' };
    }
    if (cache.mode !== 'off' && storableRejection(r)) {
      cache.verifyFail(key, symbol, r.err);
      cache.putFail(key, symbol, r.err);
    }
    return r;
  };
  /** Resolve the namespace EAGERLY, before any candidate compiles. */
  const warmCache = (): void => cache.warm();

  const PROBE = 'int asmlift_prelude_probe;\n';
  let preludeOk: boolean | undefined;
  const probePrelude = (symbol: string): boolean => {
    if (execute(C_TYPEDEFS + PROBE_DECLS + PROBE, symbol, 'c').ok) {
      return true;
    }
    return !execute(PROBE, symbol, 'c').ok;
  };
  // The async twin, memoized as a PROMISE: N workers starting together would otherwise each see
  // an unset `preludeOk` and probe the world N times.
  let probing: Promise<boolean> | undefined;
  const probeAsync = (symbol: string): Promise<boolean> =>
    (probing ??= (async () => {
      const probeSlot = slot();
      if ((await executeIn(probeSlot(), C_TYPEDEFS + PROBE_DECLS + PROBE, symbol, 'c')).ok) {
        return true;
      }
      return !(await executeIn(probeSlot(), PROBE, symbol, 'c')).ok;
    })());

  // headers world ⇒ BOTH the prelude and the synthesized declarations drop — the injected
  // headers own the types and every declaration (a second copy is a C89 collision).
  // EXCEPT the address-cast macro defines: a duplicate `#define` with an identical body is
  // legal C (unlike a duplicate typedef or struct), and the headers world does NOT
  // necessarily supply them — a PREPROCESSED context has no macros left at all, so dropping
  // these turns a macro-named candidate into `undeclared identifier`. They are emitted in
  // both worlds for that reason.
  // The self-declared half is CORE's composition (declare.ts selfDeclaredContext), not a second
  // copy of `C_TYPEDEFS + decls` — the webapp's scorer calls the same function, so the two
  // scoring worlds cannot drift on what a candidate was compiled in.
  const preludeFor = (world: boolean, declarations?: string): string =>
    world ? selfDeclaredContext(declarations) : macroDefinesOf(declarations);
  const unwrap = (r: Verdict): string => {
    if (!r.ok) {
      throw new Error(r.err);
    }
    return r.cmd;
  };

  return {
    compile: (source, symbol, backendId, declarations) => {
      let prelude = '';
      if (backendId !== 'pascal') {
        preludeOk ??= probePrelude(symbol);
        prelude = preludeFor(preludeOk, declarations);
      }
      warmCache();
      return unwrap(executeCached(prelude + source, symbol, backendId === 'pascal' ? 'p' : 'c'));
    },
    selfDeclared: () => preludeOk,
    worker: () => {
      const mine = slot();
      return async (source, symbol, backendId, declarations) => {
        let prelude = '';
        if (backendId !== 'pascal') {
          preludeOk ??= await probeAsync(symbol);
          prelude = preludeFor(preludeOk, declarations);
        }
        warmCache();
        return unwrap(await executeInCached(mine, prelude + source, symbol, backendId === 'pascal' ? 'p' : 'c'));
      };
    },
  };
}

/** The synchronous candidate compiler alone — the shape every non-pooled caller wants. */
export function compileFromCommand(template: string, opts: CompileCommandOptions = {}): CandidateCompiler {
  return compilersFromCommand(template, opts).compile;
}
