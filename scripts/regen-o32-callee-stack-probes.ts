// Regenerate the committed O32 probes read by `packages/core/test/callee-stack-words.test.ts`: an
// undeclared `jal` whose callee's body, lifted from the same object, sizes its stack arguments
// (frontend/callee-body.ts `CalleeStackWords`, the MIPS licence in frontend/mips.ts `lowerJal`).
// `nine` loads five incoming words at entry, `br6` its one only on a branch; `call9`/`call_br`
// stage the words their callee loads, `krmore` one more than `kr` loads. Each compiler at its
// canonical flags.
//
//   ASMLIFT_IDO_CC=… ASMLIFT_KMC_DIR=… ASMLIFT_GCC272_DIR=… npx tsx scripts/regen-o32-callee-stack-probes.ts
//
// Writes `<slug>-calleestack.asm` (the objdump listing) and `<slug>-calleestack.txt` (its
// `objdump -s -r -t`, which names each `jal`'s callee by relocation), each with a provenance header.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { TOOLCHAIN_TARGETS } from '../packages/core/src/target';
import {
  GCC272_TOOLCHAIN,
  GCC_KMC_TOOLCHAIN,
  IDO_TOOLCHAIN,
  compileMipsGcc272Target,
  compileMipsGccTarget,
  compileMipsTarget,
  mipsObjdumpText,
} from '../packages/toolchains/src/index';

const CORPUS = join(import.meta.dirname, '..', 'packages', 'core', 'test', 'corpus');
const SOURCE = 'probe-o32-callee-stack.c';
const FIRST = 'nine';

const PROBES = [
  {
    slug: 'ido71',
    target: 'ido7.1',
    what: 'MIPS_IDO (ido7.1), binary from $ASMLIFT_IDO_CC',
    t: IDO_TOOLCHAIN,
    compile: compileMipsTarget,
  },
  {
    slug: 'gcc272kmc',
    target: 'gcc2.7.2kmc',
    what: 'MIPS_GCC (gcc2.7.2kmc), binary from $ASMLIFT_KMC_DIR',
    t: GCC_KMC_TOOLCHAIN,
    compile: compileMipsGccTarget,
  },
  {
    slug: 'gcc272',
    target: 'gcc2.7.2',
    what: 'MIPS_GCC (gcc2.7.2), binary from $ASMLIFT_GCC272_DIR',
    t: GCC272_TOOLCHAIN,
    compile: compileMipsGcc272Target,
  },
] as const;

const source = readFileSync(join(CORPUS, SOURCE), 'utf8');
for (const p of PROBES) {
  const flags = TOOLCHAIN_TARGETS[p.target].canonicalFlags;
  const { obj, asm } = p.compile(source, FIRST, flags);
  // objdump prints the object's PATH, and the compile runs in a per-content temp dir — normalised
  // so a regeneration is no diff and no local directory reaches the repo
  const norm = (text: string) =>
    text.replace(/^\S*\.o:(\s+file format)/m, 'probe.o:$1').replace(/\S*\/asmlift-[^/\s]*\/(\w+\.c)/g, '$1');
  const header = (objdump: string) =>
    `# GENERATED by scripts/regen-o32-callee-stack-probes.ts — do not hand-edit.\n` +
    `# source    : packages/core/test/corpus/${SOURCE}\n` +
    `# toolchain : ${p.what}\n` +
    `# cc flags  : ${[...p.t.harnessFlags, ...flags].join(' ')}\n` +
    `# objdump   : ${objdump}\n` +
    `# read by   : packages/core/test/callee-stack-words.test.ts\n`;
  const dis = `${p.t.objdump.replace(/^\S*\//, '')} ${p.t.objdumpFlags.join(' ')}`;
  writeFileSync(join(CORPUS, `${p.slug}-calleestack.asm`), header(dis) + norm(asm));
  const dump = mipsObjdumpText(obj, p.t.objdump, FIRST);
  writeFileSync(
    join(CORPUS, `${p.slug}-calleestack.txt`),
    header(`${p.t.objdump.replace(/^\S*\//, '')} -s -r -t`) + norm(dump),
  );
  console.log(`wrote ${p.slug}-calleestack.{asm,txt}`);
}
