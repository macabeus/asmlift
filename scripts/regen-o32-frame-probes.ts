// Regenerate the committed O32 frame-layout probe objects read by
// `packages/core/test/o32-frame-probes.test.ts`.
//
// WHY A SCRIPT AND NOT A NOTE. `compilerBehaviors.o32LocalArea` (target.ts) is a layout fact the
// MIPS frontend's frame partition rests on, and a partition drawn wrong is an object declared at
// the wrong bytes — so it owes the compiled objects it was read off, re-measurable and not only
// re-readable. The two toolchains that share `MIPS_GCC` are compiled at their own flags (Snowboard
// Kids 2's Kyoto build at -O2, Mario Party 3's at -O1), taken from `@asmlift/core` rather than
// retyped, so a flag change shows up here as a diff in the regenerated fixtures.
//
//   ASMLIFT_IDO_CC=… ASMLIFT_KMC_DIR=… ASMLIFT_GCC272_DIR=… npx tsx scripts/regen-o32-frame-probes.ts
//
// Rewrites the three `*-o32frame.txt` fixtures in place, each with a provenance header naming the
// compiler as an `ASMLIFT_*` env name (never a machine path), its flags, and the objdump command.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { TOOLCHAIN_TARGETS } from '../packages/core/src/target';
import {
  GCC272_TOOLCHAIN,
  GCC_KMC_TOOLCHAIN,
  IDO_TOOLCHAIN,
  compileMipsGcc272Target,
  compileMipsGccTarget,
  compileMipsTarget,
} from '../packages/toolchains/src/index';

const CORPUS = join(import.meta.dirname, '..', 'packages', 'core', 'test', 'corpus');
const SOURCE = 'probe-o32-frame.c';

const TOOLCHAINS = [
  {
    slug: 'ido71',
    envVar: 'ASMLIFT_IDO_CC',
    description: 'MIPS_IDO (ido7.1)',
    harness: IDO_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['ido7.1'].canonicalFlags,
    objdump: `${IDO_TOOLCHAIN.objdump} ${IDO_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: compileMipsTarget,
  },
  {
    slug: 'gcc272kmc',
    envVar: 'ASMLIFT_KMC_DIR',
    description: "MIPS_GCC (gcc2.7.2kmc — Snowboard Kids 2's Kyoto build, -O2)",
    harness: GCC_KMC_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['gcc2.7.2kmc'].canonicalFlags,
    objdump: `${GCC_KMC_TOOLCHAIN.objdump} ${GCC_KMC_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: compileMipsGccTarget,
  },
  {
    slug: 'gcc272',
    envVar: 'ASMLIFT_GCC272_DIR',
    description: "MIPS_GCC (gcc2.7.2 — Mario Party 3's build, -O1)",
    harness: GCC272_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['gcc2.7.2'].canonicalFlags,
    objdump: `${GCC272_TOOLCHAIN.objdump} ${GCC272_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: compileMipsGcc272Target,
  },
] as const;

for (const t of TOOLCHAINS) {
  // The probe's first function scopes the dump; objdump prints the whole `.text`, every probe in it.
  const { asm } = t.compile(readFileSync(join(CORPUS, SOURCE), 'utf8'), 'leafarr', t.cflags);
  // objdump prints the object's PATH, and the compile runs in a per-content temp dir — normalised
  // so a regeneration is no diff and no local directory reaches the repo.
  const body = asm.replace(/^\S*ref\.o:(\s+file format)/m, 'probe.o:$1');
  const header =
    `# GENERATED by scripts/regen-o32-frame-probes.ts — do not hand-edit.\n` +
    `# source    : packages/core/test/corpus/${SOURCE}\n` +
    `# toolchain : ${t.description}, binary from $${t.envVar}\n` +
    `# cc flags  : ${[...t.harness, ...t.cflags].join(' ')}\n` +
    `# objdump   : ${t.objdump}\n` +
    `# read by   : packages/core/test/o32-frame-probes.test.ts\n`;
  const out = join(CORPUS, `${t.slug}-o32frame.txt`);
  writeFileSync(out, header + body);
  console.log(`wrote ${out}`);
}
