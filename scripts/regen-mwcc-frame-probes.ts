// Regenerate the committed mwcc frame-layout probe objects read by
// `packages/core/test/mwcc-frame-probes.test.ts`.
//
// WHY A SCRIPT AND NOT A NOTE. `compilerBehaviors.linkageLocalArea` (target.ts) is a layout fact the
// PPC frontend's frame partition rests on, and a partition drawn wrong is an object declared at the
// wrong bytes — so it owes the compiled objects it was read off, re-measurable and not only
// re-readable. Each build is compiled at the flags its benchmark rows use: mwcc_242_81 at its
// canonical flags and at Mario Party 4's (whose later `-O0,p` is the level the compiler acts on),
// mwcc_247_107 at Mario Party 4's, and mwcc_233_163n at Pikmin's in C.
//
//   ASMLIFT_MWCC_ROOT=… npx tsx scripts/regen-mwcc-frame-probes.ts
//
// Rewrites the four `mwcc*-frame.txt` fixtures in place, each with a provenance header naming the
// build, its flags and the objdump command (never a machine path).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { TOOLCHAIN_TARGETS } from '../packages/core/src/target';
import { MWCC_PPC_TOOLCHAIN, type MwccToolchainId, compilePpcTarget } from '../packages/toolchains/src/index';

const CORPUS = join(import.meta.dirname, '..', 'packages', 'core', 'test', 'corpus');
const SOURCE = 'probe-mwcc-frame.c';

const BASE = ['-proc', 'gekko', '-align', 'powerpc', '-enum', 'int', '-fp', 'hardware', '-Cpp_exceptions', 'off'];
/** Mario Party 4's DOL unit flags as its rows store them. */
const MP4 = [
  ...BASE,
  ...['-O4,p', '-inline', 'auto', '-pragma', 'cats off', '-RTTI', 'off', '-fp_contract', 'on', '-str', 'reuse'],
  ...['-O0,p', '-char', 'unsigned', '-fp_contract', 'off', '-lang=c'],
];
/** Pikmin's unit flags as its rows store them, in C. */
const PIKMIN_C = [
  ...BASE,
  ...['-O4,p', '-inline', 'auto', '-pragma', 'cats off', '-RTTI', 'off', '-fp_contract', 'off', '-str', 'reuse'],
  ...['-RTTI', 'on', '-char', 'unsigned', '-lang=c'],
];

const BUILDS: { slug: string; mwcc: MwccToolchainId; label: string; flags: readonly string[] }[] = [
  {
    slug: 'mwcc242',
    mwcc: 'mwcc_242_81',
    label: 'canonical flags',
    flags: TOOLCHAIN_TARGETS.mwcc_242_81.canonicalFlags,
  },
  { slug: 'mwcc242mp4', mwcc: 'mwcc_242_81', label: "Mario Party 4's flags", flags: MP4 },
  { slug: 'mwcc247', mwcc: 'mwcc_247_107', label: "Mario Party 4's flags", flags: MP4 },
  { slug: 'mwcc233', mwcc: 'mwcc_233_163n', label: "Pikmin's flags, in C", flags: PIKMIN_C },
];

for (const b of BUILDS) {
  // The probe's first function scopes the dump; objdump prints the whole `.text`, every probe in it.
  const { asm } = compilePpcTarget(b.mwcc, readFileSync(join(CORPUS, SOURCE), 'utf8'), 'leafarr', b.flags);
  // objdump prints the object's PATH, and the compile runs in a per-content temp dir — normalised
  // so a regeneration is no diff and no local directory reaches the repo.
  const body = asm.replace(/^\S*ref\.o:(\s+file format)/m, 'probe.o:$1');
  const header =
    `# GENERATED by scripts/regen-mwcc-frame-probes.ts — do not hand-edit.\n` +
    `# source    : packages/core/test/corpus/${SOURCE}\n` +
    `# toolchain : ${b.mwcc} at ${b.label}, binary under $ASMLIFT_MWCC_ROOT\n` +
    `# cc flags  : ${[...MWCC_PPC_TOOLCHAIN.harnessFlags, ...b.flags].join(' ')}\n` +
    `# objdump   : ${MWCC_PPC_TOOLCHAIN.objdump} ${MWCC_PPC_TOOLCHAIN.objdumpFlags.join(' ')}\n` +
    `# read by   : packages/core/test/mwcc-frame-probes.test.ts\n`;
  const out = join(CORPUS, `${b.slug}-frame.txt`);
  writeFileSync(out, header + body);
  console.log(`wrote ${out}`);
}
