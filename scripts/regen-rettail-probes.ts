// Regenerate the committed return-tail fixtures read by `packages/core/test/cross-jumped-tail.test.ts`
// and `packages/core/test/unfolded-branch-constant.test.ts`.
//
// Two claims. `crossJumpsReturnTails` (target.ts), which compilers keep a return tail written into
// every arm ONCE (`pa`-`pf`); and `foldsBranchConstantOnTakenEdge`, which compilers fold the constant
// a branch proved into a return on its taken edge (`pg`). It is a COMPILER claim about two SOURCE spellings of one function, the tail in
// every arm and the tail written once after the construct. So, as for
// `scripts/regen-switch-spelling-probes.ts`, both spellings are compiled and the objects committed,
// and this script is what makes the pair re-measurable rather than only re-readable.
//
// Seven pairs (`corpus/probe-rettail-{pa,pb,pc,pd,pe,pf,pg}-{copies,join}.c`), five toolchains, each at its
// canonical flags taken from `@asmlift/core` and `@asmlift/toolchains` rather than retyped:
//
//   ASMLIFT_AGBCC=… ASMLIFT_KMC_DIR=… ASMLIFT_GCC272_DIR=… ASMLIFT_MWCC_ROOT=… npx tsx scripts/regen-rettail-probes.ts
//
// Needs Docker for the two GCC 2.7.2 toolchains and for CodeWarrior, as the switch-spelling script
// does. agbcc's fixture is the compiler's own `.s`. Every other lane commits a DISASSEMBLY, with the
// object path normalised to `corpus.o` so a regeneration is no diff and leaks no local directory.
// The two GCC lanes also commit the object's `objdump -s -r -t` (`.txt`), which is where a relocatable
// object names the global a load, a store or a `jal` reaches: the frontend lifts a call only with
// it (`asmData`), as the bench does.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { TOOLCHAIN_TARGETS } from '../packages/core/src/target';
import {
  TOOLCHAIN as AGBCC_TOOLCHAIN,
  GCC272_TOOLCHAIN,
  GCC_KMC_TOOLCHAIN,
  IDO_TOOLCHAIN,
  MWCC_PPC_TOOLCHAIN,
  compileMipsGcc272Target,
  compileMipsGccTarget,
  compileMipsTarget,
  compilePpcTarget,
  compileTargetAsm,
  mipsObjdumpText,
} from '../packages/toolchains/src/index';

const CORPUS = join(import.meta.dirname, '..', 'packages', 'core', 'test', 'corpus');
const READ_BY = (probe: string) =>
  probe.startsWith('pg-')
    ? 'packages/core/test/unfolded-branch-constant.test.ts'
    : 'packages/core/test/cross-jumped-tail.test.ts';
const PROBES = [
  'pa-copies',
  'pa-join',
  'pb-copies',
  'pb-join',
  'pc-copies',
  'pc-join',
  'pd-copies',
  'pd-join',
  'pe-copies',
  'pe-join',
  'pf-copies',
  'pf-join',
  'pg-copies',
  'pg-join',
] as const;
const SYMBOL = 'f';

const DISASSEMBLED = [
  {
    slug: 'ido71',
    envVar: 'ASMLIFT_IDO_CC',
    description: 'MIPS_IDO (ido7.1)',
    harness: IDO_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['ido7.1'].canonicalFlags,
    objdump: `${IDO_TOOLCHAIN.objdump} ${IDO_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: (c: string) => compileMipsTarget(c, SYMBOL, TOOLCHAIN_TARGETS['ido7.1'].canonicalFlags),
    // IDO's dump holds its temp directory in a debug section, so its lane commits none
    relocDump: null as string | null,
  },
  {
    slug: 'gcc272kmc',
    envVar: 'ASMLIFT_KMC_DIR',
    description: "MIPS_GCC (gcc2.7.2kmc — Snowboard Kids 2's Kyoto build, -O2)",
    harness: GCC_KMC_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['gcc2.7.2kmc'].canonicalFlags,
    objdump: `${GCC_KMC_TOOLCHAIN.objdump} ${GCC_KMC_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: (c: string) => compileMipsGccTarget(c, SYMBOL, TOOLCHAIN_TARGETS['gcc2.7.2kmc'].canonicalFlags),
    relocDump: GCC_KMC_TOOLCHAIN.objdump as string | null,
  },
  {
    slug: 'gcc272',
    envVar: 'ASMLIFT_GCC272_DIR',
    description: "MIPS_GCC (gcc2.7.2 — Mario Party 3's build, -O1)",
    harness: GCC272_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['gcc2.7.2'].canonicalFlags,
    objdump: `${GCC272_TOOLCHAIN.objdump} ${GCC272_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: (c: string) => compileMipsGcc272Target(c, SYMBOL, TOOLCHAIN_TARGETS['gcc2.7.2'].canonicalFlags),
    relocDump: GCC272_TOOLCHAIN.objdump as string | null,
  },
  {
    slug: 'mwcc242',
    envVar: 'ASMLIFT_MWCC_ROOT',
    description: 'PPC_MWCC (mwcc_242_81)',
    harness: MWCC_PPC_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS.mwcc_242_81.canonicalFlags,
    objdump: `${MWCC_PPC_TOOLCHAIN.objdump} ${MWCC_PPC_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: (c: string) => compilePpcTarget('mwcc_242_81', c, SYMBOL, TOOLCHAIN_TARGETS.mwcc_242_81.canonicalFlags),
    relocDump: null,
  },
] as const;

for (const probe of PROBES) {
  const src = `probe-rettail-${probe}.c`;
  const c = readFileSync(join(CORPUS, src), 'utf8');
  const agbccHeader =
    `@ GENERATED by scripts/regen-rettail-probes.ts — do not hand-edit.\n` +
    `@ source    : packages/core/test/corpus/${src}\n` +
    `@ toolchain : ARMV4T_AGBCC (gcc 2.9-arm, Thumb), binary from $ASMLIFT_AGBCC\n` +
    `@ cc flags  : ${[...AGBCC_TOOLCHAIN.harnessFlags, ...TOOLCHAIN_TARGETS.agbcc.canonicalFlags].join(' ')}\n` +
    `@ read by   : ${READ_BY(probe)}\n`;
  const agbccOut = join(CORPUS, `agbcc-rettail-${probe}.s`);
  writeFileSync(agbccOut, agbccHeader + compileTargetAsm(c, TOOLCHAIN_TARGETS.agbcc.canonicalFlags));
  console.log(`wrote ${agbccOut}`);
  for (const t of DISASSEMBLED) {
    const { obj, asm } = t.compile(c);
    const body = asm.replace(/^\S*ref\.o:(\s+file format)/m, 'corpus.o:$1');
    const header =
      `# GENERATED by scripts/regen-rettail-probes.ts — do not hand-edit.\n` +
      `# source    : packages/core/test/corpus/${src}\n` +
      `# toolchain : ${t.description}, binary from $${t.envVar}\n` +
      `# cc flags  : ${[...t.harness, ...t.cflags].join(' ')}\n` +
      `# objdump   : ${t.objdump}\n` +
      `# read by   : ${READ_BY(probe)}\n`;
    const out = join(CORPUS, `${t.slug}-rettail-${probe}.asm`);
    writeFileSync(out, header + body);
    console.log(`wrote ${out}`);
    if (t.relocDump !== null) {
      // the object's path, and the source file the symbol table names, both live in a temp dir
      const dump = mipsObjdumpText(obj, t.relocDump, SYMBOL)
        .replace(/^\S+\.o:(\s+file format)/m, 'corpus.o:$1')
        .replace(/^(0+ l\s+df \*ABS\*\s+0+ ).*$/m, '$1corpus.c');
      const dumpOut = join(CORPUS, `${t.slug}-rettail-${probe}.txt`);
      writeFileSync(dumpOut, dump);
      console.log(`wrote ${dumpOut}`);
    }
  }
}
