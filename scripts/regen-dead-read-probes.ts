// Regenerate the committed dead-read probes read by `packages/core/test/dead-reads.test.ts`.
//
// WHY A SCRIPT AND NOT A NOTE. frontend/dead-reads.ts rests on a COMPILER claim — a read still in
// the target whose value nothing uses was `volatile` in the source — and on what each compiler
// emits for one: agbcc `ldr r0, [r3, #0x8]` into a register the next statement overwrites, IDO
// `lw zero, 0(v0)`, mwcc `lwz r0, …`. A rule that rests on those owes the objects, re-measurable and
// not only re-readable. Each toolchain compiles at its canonical flags, taken from `@asmlift/core`
// rather than retyped.
//
//   ASMLIFT_AGBCC=… ASMLIFT_IDO_CC=… ASMLIFT_KMC_DIR=… ASMLIFT_MWCC_ROOT=… \
//     npx tsx scripts/regen-dead-read-probes.ts
//
// agbcc emits TEXT, so its fixture is the compiler's own `.s`; the others are objdump text, with
// a provenance header naming the compiler as an `ASMLIFT_*` env name (never a machine path).
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

import { TOOLCHAIN_TARGETS } from '../packages/core/src/target';
import {
  GCC_KMC_TOOLCHAIN,
  IDO_TOOLCHAIN,
  MWCC_PPC_TOOLCHAIN,
  TOOLCHAIN,
  compileMipsGccTarget,
  compileMipsTarget,
  compilePpcTarget,
  compileTargetAsm,
} from '../packages/toolchains/src/index';

const CORPUS = join(import.meta.dirname, '..', 'packages', 'core', 'test', 'corpus');
const SOURCE = 'probe-dead-read.c';
const READ_BY = 'packages/core/test/dead-reads.test.ts';
const source = readFileSync(join(CORPUS, SOURCE), 'utf8');

const agbccFlags = TOOLCHAIN_TARGETS.agbcc.canonicalFlags;
writeFileSync(
  join(CORPUS, 'agbcc-deadread.s'),
  `@ GENERATED by scripts/regen-dead-read-probes.ts — do not hand-edit.\n` +
    `@ source    : packages/core/test/corpus/${SOURCE}\n` +
    `@ toolchain : ARMV4T_AGBCC (gcc 2.9-arm, Thumb), binary from $ASMLIFT_AGBCC\n` +
    `@ cc flags  : ${[...TOOLCHAIN.harnessFlags, ...agbccFlags].join(' ')}\n` +
    `@ read by   : ${READ_BY}\n` +
    compileTargetAsm(source, agbccFlags),
);

const OBJECTS = [
  {
    slug: 'ido71',
    toolchain: 'MIPS_IDO (ido7.1), binary from $ASMLIFT_IDO_CC',
    harness: IDO_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['ido7.1'].canonicalFlags,
    objdump: `${basename(IDO_TOOLCHAIN.objdump)} ${IDO_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: () => compileMipsTarget(source, 'readback', TOOLCHAIN_TARGETS['ido7.1'].canonicalFlags),
  },
  {
    slug: 'gcc272kmc',
    toolchain: 'MIPS_GCC (gcc2.7.2kmc), binary from $ASMLIFT_KMC_DIR',
    harness: GCC_KMC_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS['gcc2.7.2kmc'].canonicalFlags,
    objdump: `${basename(GCC_KMC_TOOLCHAIN.objdump)} ${GCC_KMC_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: () => compileMipsGccTarget(source, 'readback', TOOLCHAIN_TARGETS['gcc2.7.2kmc'].canonicalFlags),
  },
  {
    slug: 'mwcc242',
    toolchain: 'PPC_MWCC (mwcc_242_81), binary under $ASMLIFT_MWCC_ROOT',
    harness: MWCC_PPC_TOOLCHAIN.harnessFlags,
    cflags: TOOLCHAIN_TARGETS.mwcc_242_81.canonicalFlags,
    objdump: `${basename(MWCC_PPC_TOOLCHAIN.objdump)} ${MWCC_PPC_TOOLCHAIN.objdumpFlags.join(' ')}`,
    compile: () => compilePpcTarget('mwcc_242_81', source, 'readback', TOOLCHAIN_TARGETS.mwcc_242_81.canonicalFlags),
  },
] as const;

for (const t of OBJECTS) {
  // objdump prints the object's PATH, and the compile runs in a per-content temp dir — normalised
  // so a regeneration is no diff and no local directory reaches the repo.
  const body = t.compile().asm.replace(/^\S*ref\.o:(\s+file format)/m, 'probe.o:$1');
  const header =
    `# GENERATED by scripts/regen-dead-read-probes.ts — do not hand-edit.\n` +
    `# source    : packages/core/test/corpus/${SOURCE}\n` +
    `# toolchain : ${t.toolchain}\n` +
    `# cc flags  : ${[...t.harness, ...t.cflags].join(' ')}\n` +
    `# objdump   : ${t.objdump}\n` +
    `# read by   : ${READ_BY}\n`;
  const out = join(CORPUS, `${t.slug}-deadread.txt`);
  writeFileSync(out, header + body);
  console.log(`wrote ${out}`);
}
